// Builds the theme registry, extension/themes/themes.js, from every extension/themes/<id>/theme.json, and the
// theme table in README.md. A theme is its folder: drop one in and run `npm run themes` (npm test and the
// builds check or run it too). The extension cannot list its own folders at runtime, hence this step.
//
// theme.json (see extension/themes/README.md): name, description, versions, preview, swatch, and optionally
// category, order, appearance, hue, controls, swatchFor, shared. Derived from the folder's files:
//   usesTokens  tokens.css is there: the generated map of Sitecore's UI (surfaces/) applies, coloured by it
//   hasDom      dom.js is there
//   areas       the <area>.css files present (shell, login, speak, launchpad, ee, admin)
//   shared      every other .css but bar.css, alphabetically, unless theme.json lists them in order
//   bar         bar.css is there: the theme's look for the site's postfix in Sitecore's top bar
//   previews    preview[-<version>][-dark].jpg suffixes, made by tools/previews.cjs
// node tools/themes.mjs [--check]   (--check: exit 1 if themes.js or README.md is out of date)
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const root = path.resolve(import.meta.dirname, "..");
const DIR = path.join(root, "extension", "themes");
const OUT = path.join(DIR, "themes.js");
const README = path.join(root, "README.md");

export const AREAS = ["shell", "login", "speak", "launchpad", "ee", "admin"];
export const VERSIONS = ["10.4", "10.5"];
// The picker's groups, in order. A theme without a category sits above them all; a category not listed here
// is added after these, named after its id.
const CATEGORIES = [
  { id: "everyday", name: "Everyday" },
  { id: "modern", name: "Modern" },
  { id: "retro", name: "Retro" },
  { id: "creative", name: "Creative" },
];

function load(base, id) {
  const dir = path.join(base, id);
  const fail = (msg) => { throw new Error(`extension/themes/${id}/theme.json: ${msg}`); };
  if (!/^[a-z][a-z0-9]*$/.test(id)) fail("the folder name is the theme's id: lower-case letters and digits");
  let t;
  try {
    t = JSON.parse(fs.readFileSync(path.join(dir, "theme.json"), "utf8"));
  } catch (e) {
    fail(e.message);
  }
  for (const k of ["name", "description"]) if (typeof t[k] !== "string" || !t[k]) fail(`${k} is required`);
  if (!Array.isArray(t.versions) || !t.versions.length || t.versions.some((v) => !VERSIONS.includes(v))) fail(`versions: some of ${VERSIONS.join(", ")}`);
  if (!Array.isArray(t.preview) || t.preview.length !== 3) fail("preview: three colours (panel, accent, chrome)");
  if (!t.swatch || typeof t.swatch !== "object") fail("swatch is required (see extension/popup/swatch.js)");

  const files = fs.readdirSync(dir);
  const css = files.filter((f) => f.endsWith(".css"));
  const areas = AREAS.filter((a) => css.includes(`${a}.css`));
  const others = css.filter((f) => !["tokens.css", "bar.css", ...areas.map((a) => `${a}.css`)].includes(f)).sort();
  const shared = t.shared || others;
  if (shared.length !== others.length || shared.some((f) => !others.includes(f))) fail(`shared must list exactly ${others.join(", ") || "nothing"}`);
  const previews = files
    .map((f) => /^preview((?:-\d+\.\d+)?(?:-dark)?)\.jpg$/.exec(f)?.[1])
    .filter((s) => s !== undefined)
    .sort();
  const { order, ...rest } = t;
  return {
    id, ...rest,
    usesTokens: css.includes("tokens.css"),
    hasDom: files.includes("dom.js"),
    areas, shared,
    bar: css.includes("bar.css"),
    previews,
    order: order ?? Infinity,
  };
}

export function catalog(dir = DIR) {
  const themes = fs.readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && fs.existsSync(path.join(dir, d.name, "theme.json")))
    .map((d) => load(dir, d.name));
  const categories = [...CATEGORIES];
  for (const t of themes) {
    if (t.category && !categories.some((c) => c.id === t.category)) categories.push({ id: t.category, name: t.category[0].toUpperCase() + t.category.slice(1) });
  }
  const group = (t) => (t.category ? 1 + categories.findIndex((c) => c.id === t.category) : 0);
  themes.sort((a, b) => group(a) - group(b) || a.order - b.order || a.name.localeCompare(b.name));
  return { categories, themes: themes.map(({ order, ...t }) => t) };
}

export function registry({ categories, themes } = catalog()) {
  return `// Generated by tools/themes.mjs from extension/themes/*/theme.json and each folder's files. Do not edit:
// change a theme's theme.json and run \`npm run themes\`.
(function (root) {
  const SCT = (root.SCT = root.SCT || {});
  SCT.categories = ${JSON.stringify(categories)};
  SCT.themes = [
${themes.map((t) => `    ${JSON.stringify(t)},`).join("\n")}
  ];
  if (typeof module !== "undefined") module.exports = SCT.themes;
})(globalThis);
`;
}

// The README's theme table, between <!-- themes --> and <!-- /themes -->
export function readme(text, { categories, themes } = catalog()) {
  const row = (t) => `| ${t.name} | ${t.description} |`;
  const table = [
    "| Theme | What it looks like |",
    "|---|---|",
    ...themes.filter((t) => !t.category).map(row),
    ...categories.flatMap((c) => {
      const ts = themes.filter((t) => t.category === c.id);
      return ts.length ? [`| **${c.name}** | |`, ...ts.map(row)] : [];
    }),
  ].join("\n");
  return text.replace(/(<!-- themes -->\n)[\s\S]*?(\n<!-- \/themes -->)/, `$1${table}$2`);
}

function main() {
  const check = process.argv.includes("--check");
  const c = catalog();
  const outputs = [[OUT, registry(c)], [README, readme(fs.readFileSync(README, "utf8"), c)]];
  const stale = outputs.filter(([f, text]) => !fs.existsSync(f) || fs.readFileSync(f, "utf8") !== text);
  if (check) {
    for (const [f] of stale) console.error(`${path.relative(root, f)} is out of date: run npm run themes`);
    process.exit(stale.length ? 1 : 0);
  }
  for (const [f, text] of stale) fs.writeFileSync(f, text);
  console.log(`${c.themes.length} themes${stale.length ? `, wrote ${stale.map(([f]) => path.relative(root, f)).join(" and ")}` : ", nothing to update"}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
