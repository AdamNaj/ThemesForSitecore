// Dev tool: ports Sitecore 6.6's shell stylesheets onto Sitecore 10.4 and 10.5 for the Copenhagen theme.
//
// 1. Every 10.x rule (stock, or the token layer in surfaces/shell.css) that styles an element 6.6 also
//    styled gets each of its properties put back: to 6.6's value where 6.6 set one, else `revert`.
// 2. Every class or id rule of 6.6 follows, with 6.6's own values, so it wins ties with the resets.
//
// Both go between the BEGIN/END markers of extension/themes/sitecore6/shell.css. The hand-written
// rules after the block adapt what 10.x renders differently (markup, inline styles, img src).
//
// Usage: node tools/build-sitecore6-css.mjs [sc66-website-root]
//   (default: sitecore.local.json webroots.sitecore6; 10.x stylesheets from its stock webroots.10.5 and 10.4)
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import postcss from "postcss";
import local from "./local.cjs";

const SC66 = process.argv[2] || local.need("webroots", "sitecore6");
const MODERN = [local.need("webroots", "10.5"), local.need("webroots", "10.4")];
const OUT = path.join(import.meta.dirname, "..", "extension", "themes", "sitecore6", "shell.css");
const PREFIX = 'html[data-sct-theme="sitecore6"][data-sct-surface="shell"]';
const BEGIN = "/* BEGIN generated by tools/build-sitecore6-css.mjs from a Sitecore 6.6 install. Do not edit. */";
const END = "/* END generated */";

const THEME = "sitecore/shell/Themes/Standard";
// 6.6 loads Default/<name>.css, then the browser folder's file of the same name; every
// non-IE browser got the Firefox folder.
const OLD_FILES = () => {
  const def = fs.readdirSync(`${SC66}/${THEME}/Default`).filter((f) => f.endsWith(".css")).sort((a, b) => (a === "Default.css" ? -1 : b === "Default.css" ? 1 : a.localeCompare(b)));
  const files = [];
  for (const f of def) {
    files.push(`${THEME}/Default/${f}`);
    if (fs.existsSync(`${SC66}/${THEME}/Firefox/${f}`)) files.push(`${THEME}/Firefox/${f}`);
  }
  // Application stylesheets that 10.x still ships.
  for (const rel of fs.globSync("sitecore/shell/{Applications,Controls}/**/*.css", { cwd: SC66 }).map((r) => r.replaceAll("\\", "/")).sort()) {
    if (/\/(lib|testing|webedit)\//i.test(rel)) continue;
    if (MODERN.some((m) => fs.existsSync(path.join(m, rel)))) files.push(rel);
  }
  return files;
};
const MODERN_GLOBS = [`${THEME}/Default/*.css`, `${THEME}/*.css`, "sitecore/shell/Applications/**/*.css", "sitecore/shell/Controls/**/*.css"];
const MODERN_SKIP = [/\.min\.css$/i, /\.old\.css$/i, /\/(lib|deps|testing)\//i, /page modes\/output/i, /webedit/i];

// Windows 7 defaults for the system colours 6.6 relied on; browsers no longer honour them.
const SYSTEM_COLORS = {
  threedface: "#f0f0f0", buttonface: "#f0f0f0", menu: "#f0f0f0", threedhighlight: "#ffffff", buttonhighlight: "#ffffff",
  threedshadow: "#a0a0a0", buttonshadow: "#a0a0a0", threeddarkshadow: "#696969", threedlightshadow: "#e3e3e3",
  window: "#ffffff", windowtext: "#000000", buttontext: "#000000", menutext: "#000000", captiontext: "#000000",
  infotext: "#000000", infobackground: "#ffffe1", highlight: "#3399ff", highlighttext: "#ffffff",
  activecaption: "#99b4d1", inactivecaption: "#bfcddb", inactivecaptiontext: "#434e54", graytext: "#6d6d6d",
  appworkspace: "#ababab",
};
// 6.6 images that 10.x replaced with different art at the same path.
const IMAGE_MAP = [[/\/images\/startbar\/startbutton(_h)?\.png/i, (m, h) => `/images/startbutton${h || ""}.png`]];
const LENGTH_PROPS = /^(width|height|min-width|min-height|max-width|max-height|top|right|bottom|left|margin(-\w+)?|padding(-\w+)?|line-height|font-size)$/;

const fixValue = (prop, value, dir) => {
  let v = value.replace(/url\(\s*(['"]?)(?!data:|\/|https?:)([^'")]+)\1\s*\)/gi, (_, q, rel) => `url("${path.posix.join(dir, rel)}")`);
  for (const [re, to] of IMAGE_MAP) v = v.replace(re, to);
  v = v.replace(/\b([a-z]+)\b/gi, (w) => SYSTEM_COLORS[w.toLowerCase()] || w);
  if (LENGTH_PROPS.test(prop)) v = v.replace(/(^|\s)(-?\d+(?:\.\d+)?)(?=\s|$)/g, (m, s, n) => (n === "0" || prop === "line-height" ? m : `${s}${n}px`));
  return v;
};
const keepDecl = (prop, value) =>
  !/^[*_]/.test(prop) && !/^-(ms|moz|khtml|webkit|o)-/.test(prop) && !/^(filter|zoom|behavior|scrollbar-.*)$/.test(prop) && !/progid:|expression\(/i.test(value);
const keepOldSelector = (sel) => /[.#]/.test(sel) && !/(^|\s)\.ie\b|\*\s*html|\.lang_|:lang|\[lang/i.test(sel);

// ---- selectors ----
const norm = (sel) => sel.trim().replace(/\s+/g, " ").replace(/\s*([>+~])\s*/g, " $1 ");
function compounds(sel) {
  const parts = [];
  let depth = 0, cur = "";
  for (const ch of norm(sel)) {
    if (ch === "(" || ch === "[") depth++;
    if (ch === ")" || ch === "]") depth--;
    if (!depth && (ch === " " || ch === ">" || ch === "+" || ch === "~")) {
      if (cur) parts.push(cur);
      cur = "";
      continue;
    }
    cur += ch;
  }
  if (cur) parts.push(cur);
  return parts;
}
function subject(sel) {
  const parts = compounds(sel);
  const last = parts[parts.length - 1] || "";
  const bare = last.replace(/\[[^\]]*\]|\([^)]*\)/g, "");
  const pseudoEl = (bare.match(/::?(before|after|first-line|first-letter|placeholder|selection|marker)\b/i) || [])[1] || "";
  const states = (bare.match(/:(hover|active|focus|focus-visible|focus-within|checked|disabled)\b/gi) || []).map((s) => s.toLowerCase()).sort();
  return {
    names: [...new Set([...(bare.match(/[.#][\w-]+/g) || [])])],
    states,
    pseudoEl: pseudoEl.toLowerCase(),
    ancestors: new Set(parts.slice(0, -1).join(" ").match(/[.#][\w-]+/g) || []),
    key: norm(sel).replace(/:(link|visited)\b/g, ""),
  };
}
function specificity(sel) {
  const s = norm(sel).replace(/:(is|not|where|has)\(([^)]*)\)/g, " $2 ");
  return [(s.match(/#[\w-]+/g) || []).length, (s.match(/\.[\w-]+|\[[^\]]*\]|:(?!:)[\w-]+/g) || []).length, (s.match(/(^|[\s>+~])[a-z][\w-]*|::[\w-]+/gi) || []).length];
}
const cmpSpec = (a, b) => a[0] - b[0] || a[1] - b[1] || a[2] - b[2];
const GENERIC = new Set([".header", ".panel", ".caption", ".glyph", ".chunk", ".active", ".selected", ".icon", ".title", ".label", ".value", ".cell", ".hover", ".disabled", ".scButton", ".mode"]);

// ---- shorthands ----
const SHORT = {
  background: /^background-/, font: /^(font-|line-height$)/, margin: /^margin-/, padding: /^padding-/, overflow: /^overflow-/,
  outline: /^outline-/, "list-style": /^list-style-/, "border-top": /^border-top-(color|style|width)$/, "border-right": /^border-right-(color|style|width)$/,
  "border-bottom": /^border-bottom-(color|style|width)$/, "border-left": /^border-left-(color|style|width)$/,
  border: /^border-(top|right|bottom|left|color|style|width|image)(-(color|style|width))?$/, "border-color": /^border-\w+-color$/,
  "border-style": /^border-\w+-style$/, "border-width": /^border-\w+-width$/, "border-radius": /^border-.*-radius$/,
  flex: /^flex-(grow|shrink|basis)$/, "text-decoration": /^text-decoration-/, inset: /^(top|right|bottom|left)$/,
};
const coverOf = (prop, decls) => {
  if (decls.has(prop)) return prop;
  for (const [short, re] of Object.entries(SHORT)) if (re.test(prop) && decls.has(short)) return short;
  return null;
};

// ---- parsing ----
function readRules(root, rel, { fix, keepSel, stripPrefix }) {
  const out = [];
  const text = fs.readFileSync(path.join(root, rel), "utf8").replace(/^\uFEFF/, "");
  let tree;
  try { tree = postcss.parse(text); } catch (e) { console.error(`skip ${rel}: ${e.message}`); return out; }
  const dir = "/" + path.posix.dirname(rel);
  tree.walkRules((rule) => {
    const chain = [];
    for (let p = rule.parent; p && p.type !== "root"; p = p.parent) {
      if (p.type !== "atrule") continue;
      if (/keyframes|font-face/i.test(p.name)) return;
      if (/media/i.test(p.name) && /print/i.test(p.params) && !/screen/i.test(p.params)) return;
      chain.unshift(`@${p.name} ${p.params}`);
    }
    const decls = new Map();
    rule.each((d) => {
      if (d.type !== "decl") return;
      const prop = d.prop.toLowerCase();
      if (fix && !keepDecl(prop, d.value)) return;
      decls.set(prop, { value: fix ? fixValue(prop, d.value, dir) : d.value, important: d.important });
    });
    // An empty 6.6 rule still says 6.6 drew that element plainly, so 10.x's looks on it are reset.
    if (!decls.size && !fix) return;
    // 6.6 repeats a:link and a:visited beside a to beat its own a { } rules, which the port leaves out;
    // dropping them keeps the hand-written rules able to win.
    const listed = new Set(rule.selectors.map(norm));
    const selectors = rule.selectors.filter((s) => !(fix && /:(link|visited)\b/.test(s) && listed.has(norm(s.replace(/:(link|visited)\b/g, "")))));
    for (let sel of selectors) {
      if (stripPrefix) sel = sel.replace(stripPrefix, "").trim();
      if (!sel || !keepSel(sel)) continue;
      out.push({ sel: norm(sel), chain, decls, file: rel, scope: scopeOf(rel) });
    }
  });
  return out;
}

// Each page links only the stylesheets it needs, in 6.6 as in 10.x, and under the same names. So a rule
// applies only in frames linking its file; Default.css is linked everywhere and the token layer is global.
const TOKENS = "tokens";
function scopeOf(rel) {
  if (rel.startsWith("extension/")) return TOKENS;
  const base = path.posix.basename(rel);
  return /^default\.css$/i.test(base) && rel.includes(THEME) ? null : base;
}
const scoped = (scope, lines) => (scope ? [`  &:where(:has(link[href*="/${scope}" i])) {`, ...lines.map((l) => "  " + l), "  }"] : lines);

// Everything 10.x can put into a page: markup, scripts and the strings in Sitecore's assemblies. A 6.6
// rule naming a class or id found nowhere in it can never match, so it is left out.
function corpus(root) {
  const chunks = [];
  for (const rel of fs.globSync("sitecore/**/*.{xml,aspx,ascx,js,htm,html,xaml,cshtml}", { cwd: root })) {
    if (/\.min\.js$|\/lib\/|\/deps\//i.test(rel.replaceAll("\\", "/"))) continue;
    chunks.push(fs.readFileSync(path.join(root, rel), "latin1"));
  }
  for (const dll of fs.readdirSync(path.join(root, "bin")).filter((f) => /^(sitecore|spe)\b.*\.dll$/i.test(f))) {
    const buf = fs.readFileSync(path.join(root, "bin", dll));
    // .NET keeps its strings as UTF-16 behind a length prefix, so they start at odd offsets as often as even ones.
    chunks.push(buf.toString("latin1"), buf.toString("utf16le"), buf.subarray(1).toString("utf16le"));
  }
  return chunks.join("\n").toLowerCase();
}
// ponytail: cached in the temp folder; delete sct-sc6-corpus.txt after changing an install.
const CACHE = path.join(os.tmpdir(), "sct-sc6-corpus.txt");
const CORPUS = fs.existsSync(CACHE) ? fs.readFileSync(CACHE, "latin1") : MODERN.map(corpus).join("\n");
if (!fs.existsSync(CACHE)) fs.writeFileSync(CACHE, CORPUS, "latin1");
// Sitecore's scripts add state suffixes (_Hover, _Down...) to class names at run time.
const exists = (name) => CORPUS.includes(name.slice(1).toLowerCase()) || CORPUS.includes(name.slice(1).replace(/_[A-Za-z]+$/, "").toLowerCase());
// The theme's dom.js builds 6.6's start menu header and footer, so their classes count as present.
const DOM_JS = /^\.scStartMenu(Top|Bottom)/;
const alive = (sel) => (norm(sel).match(/[.#][\w-]+/g) || []).every((n) => DOM_JS.test(n) || exists(n));

const oldRules = OLD_FILES().flatMap((rel) => readRules(SC66, rel, { fix: true, keepSel: (s) => keepOldSelector(s) && alive(s) }));
// Scoping guards against names several 6.6 files style differently (.scToolbutton, .scTitle...). A rule
// whose names only its own file uses cannot clash, and 10.x may have moved its markup to pages linking
// other files (galleries no longer link Gallery.css), so such rules apply everywhere.
{
  const namesOf = (sel) => norm(sel).match(/[.#][\w-]+/g) || [];
  const scopesByName = new Map();
  for (const r of oldRules) for (const n of namesOf(r.sel)) (scopesByName.get(n) || scopesByName.set(n, new Set()).get(n)).add(r.scope);
  for (const r of oldRules) if (r.scope && namesOf(r.sel).every((n) => scopesByName.get(n).size === 1)) r.scope = null;
}

const modernRules = [];
for (const root of MODERN) {
  for (const g of MODERN_GLOBS) {
    for (const rel of fs.globSync(g, { cwd: root }).map((r) => r.replaceAll("\\", "/")).sort()) {
      if (MODERN_SKIP.some((r) => r.test(rel))) continue;
      modernRules.push(...readRules(root, rel, { fix: false, keepSel: () => true }));
    }
  }
}
modernRules.push(...readRules(".", "extension/surfaces/shell.css", {
  fix: false,
  keepSel: (s) => !/^\[/.test(s),
  stripPrefix: /^html\[data-sct-tokens\](\[[^\]]*\])*\s*/,
}));

// 6.6 rules indexed by subject name.
const byName = new Map();
for (const r of oldRules) {
  r.subj = subject(r.sel);
  r.spec = specificity(r.sel);
  for (const n of r.subj.names) {
    if (!byName.has(n)) byName.set(n, []);
    byName.get(n).push(r);
  }
}
const oldKeys = new Set(oldRules.map((r) => r.subj.key));

// 6.6 rules that style the element a modern selector picks.
function matches(sel, scope) {
  const inScope = (r) => r.scope === null || r.scope === scope;
  const s = subject(sel);
  if (!s.names.length) return oldRules.filter((r) => inScope(r) && r.subj.key === s.key);
  const found = new Set();
  for (const n of s.names) {
    for (const r of byName.get(n) || []) {
      if (!inScope(r)) continue;
      const t = r.subj;
      if (t.pseudoEl !== s.pseudoEl) continue;
      if (!t.states.every((x) => s.states.includes(x))) continue;
      if (!t.names.every((x) => s.names.includes(x))) continue;
      // A generic class name only counts in the same surroundings.
      if (t.names.every((x) => GENERIC.has(x)) && ![...t.ancestors].some((a) => s.ancestors.has(a) || s.names.includes(a))) continue;
      found.add(r);
    }
  }
  return [...found].sort((a, b) => cmpSpec(a.spec, b.spec) || oldRules.indexOf(a) - oldRules.indexOf(b));
}

// Rules are nested in the theme prefix, so html-anchored selectors attach to it with &.
const block = (chain, sel, body) => {
  const s = /^html\b/i.test(sel) ? "&" + sel.replace(/^html/i, "") : sel;
  const rule = `  ${s} { ${body.join("; ")}; }`;
  return chain.length ? `  ${chain.join(" { ")} {\n  ${rule}\n  ${"}".repeat(chain.length)}` : rule;
};

// 10.x lays its pages out in CSS where 6.6 used tables, so only looks and spacing are reset:
// position, size, display, flex and overflow stay 10.x's.
const RESETTABLE = /^(color|background(-[\w-]+)?|border(-[\w-]+)?|outline(-[\w-]+)?|box-shadow|text-shadow|font(-[\w-]+)?|line-height|text-(decoration|transform|align|overflow|indent)(-[\w-]+)?|letter-spacing|word-spacing|white-space|vertical-align|cursor|opacity|filter|list-style(-[\w-]+)?|padding(-[\w-]+)?|margin(-[\w-]+)?|(min|max)-(width|height)|fill|stroke|appearance|caret-color|accent-color)$/;

// ---- 1. resets for modern rules on 6.6's elements ----
const resets = new Map();
const oldScopes = [...new Set(oldRules.map((r) => r.scope).filter(Boolean))];
for (const r of modernRules) {
  if (/\.lang_|\.ie\d*\b/.test(r.sel)) continue;
  // A token-layer rule applies on every page, so it is reset once per kind of page 6.6 had.
  for (const scope of r.scope === TOKENS ? [null, ...oldScopes] : [r.scope]) resetRule(r, scope);
}
function resetRule(r, scope) {
  const subj = subject(r.sel);
  const hits = matches(r.sel, scope);
  // A pseudo-element 6.6 never drew on an element it styled is switched off whole.
  const extraPseudo = !hits.length && /^(before|after)$/.test(subj.pseudoEl) && subj.names.some((n) => byName.has(n));
  if (!hits.length && !extraPseudo) return;
  // a token rule's per-page reset is only worth it where that page's own 6.6 rules take part
  if (r.scope === TOKENS && scope && !hits.some((h) => h.scope === scope)) return;
  // a:link and a:visited only add weight here; folded into the plain selector they still beat 10.x's rule
  const sel = r.sel.replace(/:(link|visited)\b/g, "") || r.sel;
  // Back to values every 6.6 page shared, the reset can apply on every page; it stays scoped only when
  // the values come from one page's own stylesheet.
  const own = hits.some((h) => h.scope) ? scope : null;
  const key = [own, ...r.chain, sel].join(" || ");
  const body = resets.get(key) || { scope: own, chain: r.chain, sel, decls: new Map() };
  if (extraPseudo) {
    body.decls.set("content", "content: none !important");
  } else {
    const merged = new Map();
    for (const h of hits) for (const [p, d] of h.decls) merged.set(p, d);
    for (const [prop, d] of r.decls) {
      const imp = d.important ? " !important" : "";
      const cover = coverOf(prop, merged);
      if (cover) body.decls.set(cover, `${cover}: ${merged.get(cover).value}${imp || (merged.get(cover).important ? " !important" : "")}`);
      else if (RESETTABLE.test(prop)) body.decls.set(prop, `${prop}: revert${imp}`);
    }
  }
  if (body.decls.size) resets.set(key, body);
}

// ---- 2. the 6.6 rules ----
// In 6.6's own order: a selector restated later (a:hover after a, a:active group) must stay later, so
// rules are merged only with the one right before them.
const port = [];
const firstByKey = new Map();
for (const r of oldRules) {
  const key = [r.scope, ...r.chain, r.sel].join(" || ");
  const last = port[port.length - 1];
  const body = last && last.key === key ? last : { key, scope: r.scope, chain: r.chain, sel: r.sel, decls: new Map(), file: r.file };
  for (const [p, d] of r.decls) body.decls.set(p, `${p}: ${d.value}${d.important ? " !important" : ""}`);
  if (body !== last) port.push(body);
  if (!firstByKey.has(key)) firstByKey.set(key, body);
}

// A reset on the very selector 6.6 also used goes into that 6.6 rule instead, ahead of 6.6's values.
for (const [key, b] of resets) {
  const p = firstByKey.get(key);
  if (!p) continue;
  const own = new Set(p.decls.keys());
  p.decls = new Map([...[...b.decls].filter(([prop]) => !own.has(prop)), ...p.decls]);
  resets.delete(key);
}

const groups = (bodies, label) => {
  const byScope = new Map();
  for (const b of bodies) {
    if (!byScope.has(b.scope)) byScope.set(b.scope, []);
    byScope.get(b.scope).push(b);
  }
  const out = [];
  for (const [scope, list] of byScope) {
    out.push("", `  /* ---- ${label(scope, list)} ---- */`);
    out.push(...scoped(scope, list.map((b) => block(b.chain, b.sel, [...b.decls.values()]))));
  }
  return out;
};
const lines = [BEGIN, `${PREFIX} {`];
lines.push(...groups(resets.values(), (scope) => `10.x rules on elements 6.6 styled, back to 6.6's values: ${scope || "every page"}`));
lines.push(...groups(port.filter((b) => b.decls.size), (scope, list) => `6.6: ${[...new Set(list.map((b) => b.file))].join(", ")}`));
lines.push("}", END);

const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
const at = current.indexOf(BEGIN), end = current.indexOf(END);
const next = at >= 0 && end > at ? current.slice(0, at) + lines.join("\n") + current.slice(end + END.length) : lines.join("\n") + "\n" + current;
fs.writeFileSync(OUT, next);
console.log(`${resets.size} resets, ${port.length} 6.6 rules, ${oldKeys.size} 6.6 selectors`);
